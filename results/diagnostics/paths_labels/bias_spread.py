"""Spread and confidence intervals of the per-option relative bias of the 504-date
labels of results/two_per_day, for the in-sample, out-of-sample and hybrid (default)
labels against the American PDE. Per option b = (mean of 100 labels - PDE) / |PDE|,
over the options the report uses (|PDE| >= 1 % of the largest, non-exact label).
Writes bias_spread.md; run from the repository root."""
import sys
sys.path.insert(0, ".")
import numpy as np, pandas as pd
from scipy import stats
import experiments.two_per_day_report as T

VERSIONS = [("IS", lambda q: q + "_ins"), ("OOS", lambda q: q + "_oos"), ("Hyb", lambda q: q)]
SETS = [("random", "40 sampled puts"), ("check", "35 check puts")]
B = 4000
rng = np.random.default_rng(1)

res = {}
for s, _ in SETS:
    lab = pd.read_parquet(f"results/two_per_day/raw/{s}_labels.parquet")
    ref = pd.read_parquet(f"results/two_per_day/raw/{s}_reference.parquet").set_index("id")
    ref["theta_pde"] = ref["theta"]
    for v, col in VERSIONS:
        po = T.per_option(lab, ref, col_of=col)
        for q in T.GREEKS:
            d = po[(po.greek == q) & po.use_rel]
            b, se = 100 * d.rel_bias.values, 100 * d.rel_se.values
            n = len(b)
            mae = np.abs(b[rng.integers(0, n, (B, n))]).mean(1)     # bootstrap over options
            res[s, v, q] = dict(
                n=n, mae=np.abs(b).mean(), lo=np.percentile(mae, 2.5), hi=np.percentile(mae, 97.5),
                mean=b.mean(), half=stats.t.ppf(0.975, n - 1) * b.std(ddof=1) / np.sqrt(n),
                sd=b.std(ddof=1), opt=1.96 * np.median(se), sig=int((np.abs(d.t) > 3).sum()))

out = []
w = out.append
w("# Spread and confidence intervals of the per-option bias (504 dates a year)\n")
w("Labels of `results/two_per_day` (300k main paths, 100 labels per option) against the American PDE; "
  "IS = in-sample, OOS = out-of-sample, Hyb = default (hybrid) label. Per option b = (mean of 100 labels − PDE) "
  "/ |PDE| in %, over the options the report uses (|PDE| ≥ 1 % of the largest, non-exact label; n options per "
  f"cell in the last table). Generated by `bias_spread.py`.\n")
w("* **MAE [95 % CI]**: mean |b| over the options (Table 1 of the summary); CI by bootstrap over the options "
  f"({B} resamples), so it covers the label noise and the choice of options.")
w("* **mean ± half-width**: mean signed b with a 95 % t-interval (direction of the bias).")
w("* **SD**: standard deviation of b over the options (variance = SD²); it includes the leftover noise of "
  "each 100-label mean.")
w("* **per-option ±**: typical 95 % half-width of one option's own bias, 1.96 × median se.")
w("* **|t| > 3**: options whose bias is more than 3 standard errors from 0 (about 0 expected from noise alone).\n")
for title, f in [("MAE [95 % CI]", lambda r: f"{r['mae']:.3g} [{r['lo']:.3g}, {r['hi']:.3g}]"),
                 ("Mean signed bias ± 95 % half-width", lambda r: f"{r['mean']:+.3g} ± {r['half']:.2g}"),
                 ("SD of the bias over the options", lambda r: f"{r['sd']:.3g}"),
                 ("Per-option 95 % half-width / options with |t| > 3 of n",
                  lambda r: f"± {r['opt']:.2g} / {r['sig']} of {r['n']}")]:
    w(f"## {title}\n")
    w("| Greek | " + " | ".join(f"{lab} {v}" for _, lab in SETS for v, _ in VERSIONS) + " |")
    w("|---|" + "---|" * (len(SETS) * len(VERSIONS)))
    for q in T.GREEKS:
        w(f"| {q} | " + " | ".join(f(res[s, v, q]) for s, _ in SETS for v, _ in VERSIONS) + " |")
    w("")
open("results/diagnostics/paths_labels/bias_spread.md", "w").write("\n".join(out))
print("\n".join(out))
