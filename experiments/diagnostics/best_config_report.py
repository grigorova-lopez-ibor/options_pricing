"""Tables and histograms of best_config.py: per option b = (mean of the labels -
American PDE) / |American PDE| in %, over the options results/two_per_day uses
(|reference| >= 1 % of the largest, non-exact label), per Greek and option set:

* MAE of the bias with a 95 % CI (bootstrap over the options, B resamples);
* mean signed bias with a 95 % t-interval;
* SD of the bias over the options (includes the noise left in each mean);
* noise floor (false bias) sqrt(2/pi) mean se;
* options with |t| > 3 (t uses the PDE tolerance of two_per_day_report);
* bias from the Bermudan approximation (mean |Bermudan - American|, PDE);
* the same MAE of the in-sample label at 504 a year with 300k paths
  (results/two_per_day, <greek>_ins) for comparison.

Histograms: hist_<set>.png, per Greek the per-option bias b of this run, with the
504/300k in-sample label in grey.

    python experiments/diagnostics/best_config_report.py --out OUT [--dest DIR]"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy import stats  # noqa: E402

import best_config as C  # noqa: E402
import experiments.two_per_day_report as T  # noqa: E402

GREEKS = ["price", "delta", "gamma", "theta", "charm", "vega", "volga", "vanna", "rho", "phi",
          "delta_r", "delta_d"]
NAMES = {"price": "Price", "delta": "Delta", "gamma": "Gamma", "theta": "Theta", "charm": "Charm",
         "vega": "Vega", "volga": "Volga", "vanna": "Vanna", "rho": "Rho", "phi": "Phi",
         "delta_r": "dDelta/dr", "delta_d": "dDelta/dd"}
SET_NAMES = {"check": "35 check options", "random": "40 options from the input ranges"}
B = 4000
OLD = ROOT / "results" / "two_per_day" / "raw"


def rel(po: pd.DataFrame, q: str) -> pd.DataFrame:
    d = po[(po.greek == q) & po.use_rel]
    return pd.DataFrame(dict(id=d.id.values, b=100 * d.rel_bias.values, se=100 * d.rel_se.values,
                             t=d.t.values, noise=100 * d.rel_noise.values, ref=d.ref.values))


def stats_of(d: pd.DataFrame, rng) -> dict:
    b, n = d.b.values, len(d)
    if n < 2:
        return dict(n=n)
    mae = np.abs(b[rng.integers(0, n, (B, n))]).mean(1)
    half = stats.t.ppf(0.975, n - 1) * b.std(ddof=1) / np.sqrt(n)
    return dict(n=n, mae=np.abs(b).mean(), lo=np.percentile(mae, 2.5), hi=np.percentile(mae, 97.5),
                mean=b.mean(), mlo=b.mean() - half, mhi=b.mean() + half, sd=b.std(ddof=1),
                floor=np.sqrt(2 / np.pi) * d.se.mean(), sig=int((np.abs(d.t) > 3).sum()),
                noise=np.median(d.noise))


def f(x, signed=False) -> str:
    if x is None or not np.isfinite(x):
        return "–"
    s = f"{x:+.3g}" if signed else f"{x:.3g}"
    return s


def report(out: str, dest: str | None = None) -> str:
    lab, refs = C.load(out)
    dest = Path(dest) if dest else Path(out) / "best_config"
    dest.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(1)
    t = lab.groupby("set").seconds.mean()
    w = ["# Best combination on the 35 check and 40 range options\n",
         f"In-sample label, **{C.SPY} exercise dates a year, {C.N_MAIN // 1000}k main paths** (pilot "
         f"{C.N_PILOT // 1000}k), {C.REPS} labels per option ({len(lab)} labels), puts; the options of "
         "`results/two_per_day`. Per option b = (mean of the labels − American PDE) / |American PDE| "
         "in %, over the options with |reference| ≥ 1 % of the largest and a non-exact label. "
         "Generated by `experiments/diagnostics/best_config_report.py` from `raw/` "
         "(`experiments/diagnostics/best_config.py`, `scc/best_config*.qsub`).\n",
         "Columns: **MAE [95 % CI]**: mean |b|, CI by bootstrap over the options; **mean b [95 % CI]**: "
         "signed, t-interval; **SD of b**: over the options (includes the noise left in each mean); "
         "**noise floor (false bias)**: √(2/π) × mean se, the MAE an unbiased label would show; "
         "**|t| > 3**: options whose bias is more than 3 standard errors from 0; **Bermudan approx.**: "
         f"mean |Bermudan({C.SPY}) − American| (PDE); **noise**: median SD of one label; "
         "**504/300k MAE**: the in-sample label of `results/two_per_day` (504 a year, 300k paths).\n",
         "Time per label (mean, s): " + ", ".join(f"{SET_NAMES[s]} {t.get(s, np.nan):.0f}" for s in C.SETS)
         + f"; peak memory {lab.rss_mb.max() / 1024:.1f} GB.\n"]
    rows_all, bias = [], {}
    for s in C.SETS:
        L = lab[lab["set"] == s]
        R = refs[refs["set"] == s]
        am = R[R["style"] == "american"].set_index("id").copy()
        be = R[R["style"] == "bermudan"].set_index("id").copy()
        am["theta_pde"], be["theta_pde"] = am["theta"], be["theta"]
        po = T.per_option(L, am)
        old = T.per_option(pd.read_parquet(OLD / f"{s}_labels.parquet"),
                           pd.read_parquet(OLD / f"{s}_reference.parquet").set_index("id")
                           .assign(theta_pde=lambda x: x["theta"]), col_of=lambda q: q + "_ins")
        w.append(f"## {SET_NAMES[s]}\n")
        w.append("| Greek | options | MAE [95 % CI] | mean b [95 % CI] | SD of b | noise floor (false bias) "
                 "| \\|t\\| > 3 | Bermudan approx. | noise | 504/300k MAE |")
        w.append("|---|---|---|---|---|---|---|---|---|---|")
        for q in GREEKS:
            d, o = rel(po, q), rel(old, q)
            st, so = stats_of(d, rng), stats_of(o, rng)
            ids = d.id.values
            gap = (100 * (be.loc[ids, q] - am.loc[ids, q]).abs() / am.loc[ids, q].abs()).mean() if len(ids) else np.nan
            bias[s, q] = (d.b.values, o.b.values)
            if st["n"] < 2:
                continue
            w.append(f"| {NAMES[q]} | {st['n']} | {f(st['mae'])} [{f(st['lo'])}, {f(st['hi'])}] | "
                     f"{f(st['mean'], True)} [{f(st['mlo'], True)}, {f(st['mhi'], True)}] | {f(st['sd'])} | "
                     f"{f(st['floor'])} | {st['sig']} of {st['n']} | {f(gap)} | {f(st['noise'])} | "
                     f"{f(so.get('mae'))} |")
            rows_all.append(dict(set=s, greek=q, **st, bermudan_approx=gap, mae_504_300k=so.get("mae")))
        w.append("")
        po.assign(set=s).to_csv(dest / f"per_option_{s}.csv", index=False)
    w.append("Histograms of the per-option bias: `hist_check.png`, `hist_random.png` "
             "(this run in colour, the 504/300k in-sample label in grey).\n")
    pd.DataFrame(rows_all).to_csv(dest / "summary_table.csv", index=False)
    text = "\n".join(w)
    (dest / "report.md").write_text(text)
    histograms(bias, dest)
    return text


def histograms(bias: dict, dest: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    for s in C.SETS:
        fig, axes = plt.subplots(3, 4, figsize=(15, 10))
        for ax, q in zip(axes.ravel(), GREEKS):
            new, old = bias.get((s, q), (np.array([]), np.array([])))
            both = np.concatenate([new, old]) if len(new) + len(old) else np.array([0.0])
            lo, hi = np.percentile(both, [1, 99]) if len(both) > 4 else (both.min(), both.max())
            lo, hi = min(lo, -1e-3), max(hi, 1e-3)
            edges = np.linspace(lo, hi, 21)
            ax.hist(np.clip(old, lo, hi), bins=edges, color="0.75", label="504/yr, 300k (earlier)")
            ax.hist(np.clip(new, lo, hi), bins=edges, histtype="step", lw=2, color="C0",
                    label=f"{C.SPY}/yr, {C.N_MAIN // 1000}k")
            ax.axvline(0, color="k", lw=0.8)
            if len(new):
                ax.axvline(new.mean(), color="C3", lw=1.2, ls="--", label="mean (this run)")
            ax.set_title(f"{NAMES[q]}: MAE {np.abs(new).mean():.3g} %" if len(new) else NAMES[q], fontsize=10)
            ax.set_xlabel("bias, % of |American|", fontsize=8)
            ax.tick_params(labelsize=8)
        axes.ravel()[0].legend(fontsize=7)
        fig.suptitle(f"Per-option bias of the in-sample label, {SET_NAMES[s]} "
                     f"(values beyond the 1st/99th percentile are shown at the edges)")
        fig.tight_layout()
        fig.savefig(dest / f"hist_{s}.png", dpi=110)
        plt.close(fig)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="best_config_out")
    p.add_argument("--dest", default=None)
    a = p.parse_args()
    print(report(a.out, a.dest))
